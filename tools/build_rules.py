#!/usr/bin/env python3
"""Build Doorstep's rules.txt from the IEEE oui.csv.

Usage: python3 tools/build_rules.py oui.csv > rules.txt

Each brand is matched against the CSV's "Organization Name" column only
(never the address column). Brands tagged other=True are rolled into the
tally's "Other" line on the Flipper.
"""
import csv
import re
import sys

# (brand, organization-name regex, other?)
# Strict on purpose: only organizations whose hardware is mostly cameras,
# doorbells or camera-centric security systems. Parent companies with huge
# non-camera catalogs (Amazon, Google, NETGEAR, Xiaomi, Tuya, Espressif,
# TP-Link, Logitech, Ubiquiti) are left out; see README "Brand rules".
BRANDS = [
    ("Ring",       r"^Ring LLC",                                   False),
    ("Blink",      r"^Blink by Amazon",                            False),
    ("Nest",       r"^Nest Labs",                                  False),
    ("Arlo",       r"^Arlo Technology",                            False),
    ("Wyze",       r"^Wyze Labs",                                  False),
    ("Eufy",       None,                                           False),  # no IEEE OUI
    ("Vivint",     r"^Vivint",                                     False),
    ("SimpliSafe", r"^SimpliSafe",                                 False),
    ("Hikvision",  r"Hikvision|^Hangzhou Ezviz|^Hangzhou Microimage", False),
    ("Dahua",      r"^Zhejiang Dahua|^Hangzhou Huacheng",          False),
    ("Reolink",    r"^Reolink",                                    False),
    # Rolled into "Other"
    ("SkyBell",    r"^SKYBELL|^SkyBell",                           True),
    ("Canary",     r"^Canary Connect",                             True),
    ("Lorex",      r"^Lorex",                                      True),
    ("Swann",      r"^Swann",                                      True),
    ("Amcrest",    r"^Amcrest",                                    True),
    ("NightOwl",   r"^Night Owl",                                  True),
    ("Zmodo",      r"^Zmodo",                                      True),
    ("AlarmCom",   r"^Alarm\.com",                                 True),
    ("YI",         r"^Shanghai Xiaoyi|^Shanghai Imilab",           True),
    ("Axis",       r"^Axis Communications",                        True),
    ("Hanwha",     r"^Hanwha Vision|^HANWHA VISION|^SAMSUNG TECHWIN", True),
    ("Vivotek",    r"^Vivotek",                                    True),
    ("Mobotix",    r"^Mobotix",                                    True),
    ("Uniview",    r"^Zhejiang Uniview",                           True),
    ("Verkada",    r"^Verkada",                                    True),
]

PER_LINE = 12  # keep lines short; repeated brand lines are merged by the app


def main(path):
    found = {b: [] for b, _, _ in BRANDS}
    with open(path, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            org = row["Organization Name"].strip()
            for brand, rx, _ in BRANDS:
                if rx and re.search(rx, org, re.I):
                    found[brand].append(row["Assignment"].upper())
                    break  # first matching brand wins

    out = sys.stdout
    out.write("# Doorstep rules - generated by tools/build_rules.py from IEEE oui.csv\n")
    out.write("# Brand [other] = prefixes: <6-hex> ...   names: <substring> ...\n")
    out.write("# Repeated brand lines are merged. Lines starting with # are ignored.\n")
    for brand, _, other in BRANDS:
        tag = " [other]" if other else ""
        pfx = sorted(set(found[brand]))
        if not pfx:
            out.write(f"{brand}{tag} = prefixes:\n")
            continue
        for i in range(0, len(pfx), PER_LINE):
            out.write(f"{brand}{tag} = prefixes: {' '.join(pfx[i:i + PER_LINE])}\n")
    for brand, _, _ in BRANDS:
        sys.stderr.write(f"{brand:11s} {len(set(found[brand]))}\n")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "oui.csv")
